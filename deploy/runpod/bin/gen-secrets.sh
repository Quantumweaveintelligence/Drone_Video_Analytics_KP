#!/usr/bin/env bash
# gen-secrets.sh <secrets-dir>
# First boot only: generates every secret of the pod into <dir>/dvas.env and one
# random password per test user into <dir>/users.json (both chmod 600).
# Never overwrites existing files. BACK BOTH FILES UP OFFLINE right after first
# boot — losing FACE_VECTOR_ENCRYPTION_KEY makes stored face embeddings unreadable.
set -euo pipefail
DIR="${1:?usage: gen-secrets.sh <secrets-dir>}"
mkdir -p "$DIR"; chmod 700 "$DIR" 2>/dev/null || true
umask 077

PY="$(command -v python3)"
rand() { "$PY" -c 'import secrets,string;a=string.ascii_letters+string.digits;print("".join(secrets.choice(a) for _ in range(int(__import__("sys").argv[1]))))' "${1:-32}"; }
hex32() { "$PY" -c 'import secrets;print(secrets.token_hex(32))'; }

if [ ! -s "$DIR/dvas.env" ]; then
  cat > "$DIR/dvas.env" <<ENV
# Generated by gen-secrets.sh on $(date -Is). Real environment variables
# (e.g. RunPod Secrets / template env) take precedence over these values.
KC_DB_PASSWORD=$(rand 32)
DVAS_DB_PASSWORD=$(rand 32)
KEYCLOAK_ADMIN=admin
KEYCLOAK_ADMIN_PASSWORD=$(rand 32)
KC_CLIENT_SECRET=$(rand 32)
ADMIN_CLIENT_ID=dvas-admin-service
ADMIN_CLIENT_SECRET=$(rand 32)
MINIO_ACCESS_KEY=dvas$(rand 12)
MINIO_SECRET_KEY=$(rand 40)
ANALYTICS_SERVICE_KEY=$(rand 48)
DVAS_SERVICE_KEY=$(rand 48)
EDGE_API_KEY=$(rand 48)
JWT_SECRET=$(rand 48)
FACE_VECTOR_ENCRYPTION_KEY=$(hex32)
DRONE_IDS=DRONE_KL_001,DRONE_KL_002,DRONE_KL_003,DRONE_KL_004,DRONE_KL_005,DRN-001,DRN-002,DRN-003,DRN-004,DRN-005
ENV
  chmod 600 "$DIR/dvas.env" 2>/dev/null || true
  echo "[gen-secrets] wrote $DIR/dvas.env"
fi

# Keys added after a pod's first boot are appended (existing values are never changed)
add_missing() { # KEY VALUE
  grep -q "^$1=" "$DIR/dvas.env" || { echo "$1=$2" >> "$DIR/dvas.env"; echo "[gen-secrets] added $1"; }
}
add_missing DVAS_REPORT_DB_PASSWORD "$(rand 32)"   # read-only analytics login for reports (R2 / Q6)

if [ ! -s "$DIR/users.json" ]; then
  "$PY" - "$DIR/users.json" <<'PYEOF'
import json, secrets, string, sys
alphabet = string.ascii_letters + string.digits
def pw():
    # >= 16 chars with upper/lower/digit/symbol so any Keycloak password policy passes
    core = "".join(secrets.choice(alphabet) for _ in range(16))
    return core + secrets.choice("ABCDEFGHJKLMNPQRSTUVWXYZ") + secrets.choice("abcdefghijkmnopqrstuvwxyz") + secrets.choice("23456789") + "@"
users = [
    {"username": "control_001",  "firstName": "Control",  "lastName": "Room",          "email": "control@dvas.kp",  "role": "control-room"},
    {"username": "senior_001",   "firstName": "Senior",   "lastName": "Officer",       "email": "senior@dvas.kp",   "role": "supervisor"},
    {"username": "admin_dvas",   "firstName": "System",   "lastName": "Administrator", "email": "admin@dvas.kp",    "role": "sys-admin"},
    {"username": "operator_001", "firstName": "Operator", "lastName": "One",           "email": "operator@dvas.kp", "role": "drone-operator"},
    {"username": "operator_002", "firstName": "Operator", "lastName": "Two",           "email": "operator_002@kerala.police.in", "role": "drone-operator"},
    {"username": "operator_003", "firstName": "Operator", "lastName": "Three",         "email": "operator_003@kerala.police.in", "role": "drone-operator"},
]
for u in users:
    u["password"] = pw()
with open(sys.argv[1], "w", encoding="utf-8") as fh:
    json.dump(users, fh, indent=2)
PYEOF
  chmod 600 "$DIR/users.json" 2>/dev/null || true
  echo "[gen-secrets] wrote $DIR/users.json"
fi

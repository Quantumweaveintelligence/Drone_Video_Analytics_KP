from fpdf import FPDF
from datetime import datetime

class ReportPDF(FPDF):
    def header(self):
        # Helvetica bold 16
        self.set_font('helvetica', 'B', 16)
        # Dark blue color (#1e3a5f)
        self.set_text_color(30, 58, 95)
        # Title
        self.cell(0, 10, 'DVAS Crowd Analytics — Mission Report', 0, 1, 'C')
        # Subtitle
        self.set_font('helvetica', 'I', 12)
        self.set_text_color(100, 100, 100)
        self.cell(0, 8, 'Kerala Police — Drone Video Analytics Suite', 0, 1, 'C')
        self.ln(5)

    def footer(self):
        # Position at 1.5 cm from bottom
        self.set_y(-15)
        # Helvetica italic 8
        self.set_font('helvetica', 'I', 8)
        self.set_text_color(128, 128, 128)
        # Page number and Generation timestamp
        timestamp = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
        self.cell(0, 10, f'Generated by DVAS — Drone Video Analytics Suite | {timestamp} | Page {self.page_no()}/{{nb}}', 0, 0, 'C')

def generate_pdf_report(summary, operator, location, mission_id, model_type):
    """
    Generates a PDF mission report for crowd analytics using fpdf2.
    
    Args:
        summary (dict): Session summary with total_frames, duration_seconds, mean_count, etc.
        operator (str): Operator name.
        location (str): Location.
        mission_id (str): Mission identifier.
        model_type (str): 'csrnet_parta' or 'csrnet_partb'.
        
    Returns:
        bytes: The PDF file content.
    """
    pdf = ReportPDF()
    pdf.alias_nb_pages()
    pdf.add_page()
    
    # Set colors
    header_color = (30, 58, 95) # Dark blue #1e3a5f
    bg_color = (240, 240, 240) # Light grey
    
    # Mission Metadata Section
    pdf.set_fill_color(*header_color)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font('helvetica', 'B', 12)
    pdf.cell(0, 8, ' Mission Details', 1, 1, 'L', fill=True)
    
    pdf.set_text_color(0, 0, 0)
    pdf.set_font('helvetica', '', 10)
    
    model_name = "CSRNet Part A (Dense Crowds)" if model_type == 'csrnet_parta' else "CSRNet Part B (Static Surveillance)"
    if model_type not in ['csrnet_parta', 'csrnet_partb']:
        model_name = model_type
        
    date_str = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    
    # Table for metadata
    pdf.set_fill_color(*bg_color)
    
    metadata = [
        ('Date/Time', date_str),
        ('Operator', operator),
        ('Location', location),
        ('Mission ID', mission_id),
        ('Model Used', model_name)
    ]
    
    for k, v in metadata:
        pdf.set_font('helvetica', 'B', 10)
        pdf.cell(50, 8, f' {k}', 1, 0, 'L', fill=True)
        pdf.set_font('helvetica', '', 10)
        pdf.cell(0, 8, f' {v}', 1, 1, 'L')
        
    pdf.ln(5)
    
    # Summary Statistics Section
    pdf.set_fill_color(*header_color)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font('helvetica', 'B', 12)
    pdf.cell(0, 8, ' Summary Statistics', 1, 1, 'L', fill=True)
    
    pdf.set_text_color(0, 0, 0)
    pdf.set_fill_color(*bg_color)
    
    stats = [
        ('Total Frames Analyzed', str(summary.get('total_frames', 0))),
        ('Duration (seconds)', f"{summary.get('duration_seconds', 0.0):.1f}"),
        ('Mean Crowd Count', f"{summary.get('mean_count', 0.0):.1f}"),
        ('Min Count', str(summary.get('min_count', 0))),
        ('Max Count', str(summary.get('max_count', 0))),
        ('Std Deviation', f"{summary.get('std_dev', 0.0):.1f}"),
        ('Peak Count', str(summary.get('peak_count', 0))),
        ('Peak Timestamp', str(summary.get('peak_timestamp', 'N/A'))),
        ('Peak Frame', str(summary.get('peak_frame', 'N/A')))
    ]
    
    # Two columns for stats
    col_width = pdf.epw / 2
    for i in range(0, len(stats), 2):
        k1, v1 = stats[i]
        
        pdf.set_font('helvetica', 'B', 10)
        pdf.cell(40, 8, f' {k1}', 1, 0, 'L', fill=True)
        pdf.set_font('helvetica', '', 10)
        pdf.cell(col_width - 40, 8, f' {v1}', 1, 0, 'L')
        
        if i + 1 < len(stats):
            k2, v2 = stats[i+1]
            pdf.set_font('helvetica', 'B', 10)
            pdf.cell(40, 8, f' {k2}', 1, 0, 'L', fill=True)
            pdf.set_font('helvetica', '', 10)
            pdf.cell(col_width - 40, 8, f' {v2}', 1, 1, 'L')
        else:
            pdf.cell(col_width, 8, '', 0, 1, 'L') # Empty cell for padding
            
    pdf.ln(5)
    
    # Density Distribution Section
    pdf.set_fill_color(*header_color)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font('helvetica', 'B', 12)
    pdf.cell(0, 8, ' Density Distribution (% time)', 1, 1, 'L', fill=True)
    
    pdf.set_text_color(0, 0, 0)
    pdf.set_fill_color(*bg_color)
    
    density = summary.get('density_distribution', {})
    if density:
        for level, pct in density.items():
            pdf.set_font('helvetica', 'B', 10)
            pdf.cell(50, 8, f' {level}', 1, 0, 'L', fill=True)
            pdf.set_font('helvetica', '', 10)
            try:
                pdf.cell(0, 8, f' {float(pct):.1f}%', 1, 1, 'L')
            except ValueError:
                pdf.cell(0, 8, f' {pct}', 1, 1, 'L')
    else:
        pdf.set_font('helvetica', 'I', 10)
        pdf.cell(0, 8, ' No density distribution data available.', 1, 1, 'L')
        
    pdf.ln(5)
    
    # Alert Log Section
    pdf.set_fill_color(*header_color)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font('helvetica', 'B', 12)
    pdf.cell(0, 8, ' Alert Log', 1, 1, 'L', fill=True)
    
    pdf.set_text_color(0, 0, 0)
    
    alerts = summary.get('alert_timestamps', [])
    if not alerts:
        pdf.set_font('helvetica', 'I', 10)
        pdf.cell(0, 8, ' No alerts recorded during this mission.', 1, 1, 'L')
    else:
        pdf.set_fill_color(*bg_color)
        pdf.set_font('helvetica', 'B', 10)
        pdf.cell(20, 8, ' #', 1, 0, 'C', fill=True)
        pdf.cell(0, 8, ' Timestamp (ISO)', 1, 1, 'L', fill=True)
        
        pdf.set_font('helvetica', '', 10)
        for i, ts in enumerate(alerts, 1):
            pdf.cell(20, 8, str(i), 1, 0, 'C')
            pdf.cell(0, 8, f' {ts}', 1, 1, 'L')
            
    # Output PDF as bytes
    return pdf.output()
